import time
from multiprocessing import Pool

# Тяжелая функция, которая нагружает процессор (CPU-bound задача)
def heavy_calculation(n):
    total = 0
    for i in range(10_000_000):
        total += i * n
    return total

if __name__ == '__main__':
    # Список входных данных (например, 8 тяжелых задач)
    numbers = [1, 2, 3, 4, 5, 6, 7, 8]
    
    # === 1. ПОСЛЕДОВАТЕЛЬНОЕ ВЫПОЛНЕНИЕ (1 ядро) ===
    print("Запуск последовательного вычисления...")
    start_time = time.time()
    
    results_sync = []
    for num in numbers:
        results_sync.append(heavy_calculation(num))
        
    end_time = time.time()
    print(f"Последовательно выполнено за: {end_time - start_time:.2f} секунд\n")
    
    # === 2. ПАРАЛЛЕЛЬНОЕ ВЫПОЛНЕНИЕ (Все доступные ядра) ===
    print("Запуск параллельного вычисления через Multiprocessing...")
    start_time = time.time()
    
    # Создаем пул процессов. По умолчанию он создает столько процессов, сколько ядер у вашего CPU
    with Pool() as pool:
        # Метод pool.map автоматически распределяет список numbers по процессам
        # и собирает результаты обратно в правильном порядке
        results_async = pool.map(heavy_calculation, numbers)
        
    end_time = time.time()
    print(f"Параллельно выполнено за: {end_time - start_time:.2f} секунд")
    
    # Проверяем, что результаты идентичны
    assert results_sync == results_async, "Ошибка: результаты не совпадают!"



# Как это работает под капотом (Суть):
# Защита if __name__ == '__main__':: Как мы 
# обсуждали ранее, она обязательна. Без нее новые процессы начнут рекурсивно 
# запускать этот же скрипт сначала.

# with Pool() as pool: Менеджер контекста 
# создает команду «рабочих» (воркеров). Если у вас 4-ядерный процессор, создадутся 
# 4 независимых процесса Python.

# pool.map(): Это параллельный аналог встроенной 
# функции map(). Он берет функцию heavy_calculation и список numbers, аккуратно 
# "нарезает" этот список на части и раскидывает по запущенным процессам.
# 
# Эффект: 
# Если на одном ядре задачи выполнялись строго по очереди (одна за другой), то в 
# пуле они выполняются одновременно. На многоядерном процессоре вы увидите ускорение 
# в несколько раз.